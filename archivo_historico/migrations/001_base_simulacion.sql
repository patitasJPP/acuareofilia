BEGIN;

CREATE TABLE IF NOT EXISTS public.schema_migrations (
    version TEXT PRIMARY KEY,
    description TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.especie_ficha (
    id_especie INTEGER PRIMARY KEY
        REFERENCES public.especies(id_especie) ON DELETE RESTRICT,
    nombre_cientifico TEXT,
    temperamento TEXT,
    dieta TEXT,
    talla_adulta_cm NUMERIC(7,2) CHECK (talla_adulta_cm IS NULL OR talla_adulta_cm > 0),
    longevidad_anios NUMERIC(6,2) CHECK (longevidad_anios IS NULL OR longevidad_anios > 0),
    volumen_min_l NUMERIC(10,2) CHECK (volumen_min_l IS NULL OR volumen_min_l > 0),
    zona_agua TEXT,
    es_depredador BOOLEAN,
    es_supuesto BOOLEAN NOT NULL DEFAULT TRUE,
    fuente TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.especie_interaccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_especie_a INTEGER NOT NULL
        REFERENCES public.especies(id_especie) ON DELETE RESTRICT,
    id_especie_b INTEGER NOT NULL
        REFERENCES public.especies(id_especie) ON DELETE RESTRICT,
    tipo TEXT NOT NULL CHECK (
        tipo IN ('depredacion', 'agresividad', 'competencia_alimento', 'enfermedad', 'compatible')
    ),
    multiplicador_riesgo_min NUMERIC(12,6) NOT NULL CHECK (multiplicador_riesgo_min >= 0),
    multiplicador_riesgo_probable NUMERIC(12,6) NOT NULL CHECK (multiplicador_riesgo_probable >= 0),
    multiplicador_riesgo_max NUMERIC(12,6) NOT NULL CHECK (multiplicador_riesgo_max >= 0),
    observaciones TEXT,
    es_supuesto BOOLEAN NOT NULL DEFAULT TRUE,
    fuente TEXT NOT NULL,
    CONSTRAINT uq_especie_interaccion UNIQUE (id_especie_a, id_especie_b, tipo),
    CONSTRAINT ck_especie_interaccion_distintas CHECK (id_especie_a <> id_especie_b),
    CONSTRAINT ck_especie_interaccion_rango CHECK (
        multiplicador_riesgo_min <= multiplicador_riesgo_probable
        AND multiplicador_riesgo_probable <= multiplicador_riesgo_max
    )
);

CREATE TABLE IF NOT EXISTS public.parametro_simulacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    descripcion TEXT,
    valor_min NUMERIC(16,8) NOT NULL CHECK (valor_min >= 0),
    valor_probable NUMERIC(16,8) NOT NULL CHECK (valor_probable >= 0),
    valor_max NUMERIC(16,8) NOT NULL CHECK (valor_max >= 0),
    unidad TEXT NOT NULL,
    es_supuesto BOOLEAN NOT NULL DEFAULT TRUE,
    fuente TEXT NOT NULL,
    CONSTRAINT ck_parametro_simulacion_rango CHECK (
        valor_min <= valor_probable AND valor_probable <= valor_max
    )
);

CREATE TABLE IF NOT EXISTS public.lectura_agua (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pecera INTEGER NOT NULL
        REFERENCES public.peceras(id_pecera) ON DELETE RESTRICT,
    fecha_hora TIMESTAMPTZ NOT NULL,
    ph NUMERIC(4,2) CHECK (ph IS NULL OR ph BETWEEN 0 AND 14),
    temperatura_c NUMERIC(5,2) CHECK (temperatura_c IS NULL OR temperatura_c BETWEEN 0 AND 60),
    oxigeno_mg_l NUMERIC(8,4) CHECK (oxigeno_mg_l IS NULL OR oxigeno_mg_l >= 0),
    amoniaco_mg_l NUMERIC(8,4) CHECK (amoniaco_mg_l IS NULL OR amoniaco_mg_l >= 0),
    nitrito_mg_l NUMERIC(8,4) CHECK (nitrito_mg_l IS NULL OR nitrito_mg_l >= 0),
    nitrato_mg_l NUMERIC(8,4) CHECK (nitrato_mg_l IS NULL OR nitrato_mg_l >= 0),
    observaciones TEXT
);

CREATE TABLE IF NOT EXISTS public.registro_mortalidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pecera INTEGER NOT NULL
        REFERENCES public.peceras(id_pecera) ON DELETE RESTRICT,
    id_especie INTEGER NOT NULL
        REFERENCES public.especies(id_especie) ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    cantidad_inicial INTEGER NOT NULL CHECK (cantidad_inicial >= 0),
    cantidad_muertos INTEGER NOT NULL CHECK (cantidad_muertos >= 0),
    causa TEXT,
    observaciones TEXT,
    CONSTRAINT ck_registro_mortalidad_cantidades CHECK (cantidad_muertos <= cantidad_inicial)
);

CREATE TABLE IF NOT EXISTS public.evento_enfermedad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pecera INTEGER NOT NULL
        REFERENCES public.peceras(id_pecera) ON DELETE RESTRICT,
    id_especie INTEGER
        REFERENCES public.especies(id_especie) ON DELETE RESTRICT,
    enfermedad TEXT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    peces_afectados INTEGER CHECK (peces_afectados IS NULL OR peces_afectados >= 0),
    observaciones TEXT,
    CONSTRAINT ck_evento_enfermedad_fechas CHECK (
        fecha_fin IS NULL OR fecha_fin >= fecha_inicio
    )
);

CREATE TABLE IF NOT EXISTS public.simulacion_corrida (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    escenario TEXT NOT NULL,
    parametros_usados JSONB NOT NULL,
    etiqueta TEXT NOT NULL DEFAULT 'NO_CALIBRADO'
        CHECK (etiqueta = 'NO_CALIBRADO'),
    es_supuesto BOOLEAN NOT NULL DEFAULT TRUE,
    fuente TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.simulacion_resultado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_corrida BIGINT NOT NULL
        REFERENCES public.simulacion_corrida(id) ON DELETE CASCADE,
    id_pecera INTEGER NOT NULL
        REFERENCES public.peceras(id_pecera) ON DELETE RESTRICT,
    id_especie INTEGER NOT NULL
        REFERENCES public.especies(id_especie) ON DELETE RESTRICT,
    horas_fuera_rango NUMERIC(12,4) NOT NULL CHECK (horas_fuera_rango >= 0),
    factor_dominante TEXT,
    mortalidad_p5_pct NUMERIC(7,4) NOT NULL CHECK (mortalidad_p5_pct BETWEEN 0 AND 100),
    mortalidad_mediana_pct NUMERIC(7,4) NOT NULL CHECK (mortalidad_mediana_pct BETWEEN 0 AND 100),
    mortalidad_p95_pct NUMERIC(7,4) NOT NULL CHECK (mortalidad_p95_pct BETWEEN 0 AND 100),
    etiqueta TEXT NOT NULL DEFAULT 'NO_CALIBRADO'
        CHECK (etiqueta = 'NO_CALIBRADO'),
    es_supuesto BOOLEAN NOT NULL DEFAULT TRUE,
    fuente TEXT NOT NULL,
    CONSTRAINT uq_simulacion_resultado UNIQUE (id_corrida, id_pecera, id_especie),
    CONSTRAINT ck_simulacion_resultado_percentiles CHECK (
        mortalidad_p5_pct <= mortalidad_mediana_pct
        AND mortalidad_mediana_pct <= mortalidad_p95_pct
    )
);

