BEGIN;

CREATE TABLE IF NOT EXISTS public.simulacion_corrida (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    escenario TEXT NOT NULL,
    parametros_usados JSONB NOT NULL,
    etiqueta TEXT NOT NULL DEFAULT 'NO_CALIBRADO',
    es_supuesto BOOLEAN NOT NULL DEFAULT TRUE,
    fuente TEXT NOT NULL,
    CONSTRAINT simulacion_corrida_pkey PRIMARY KEY (id),
    CONSTRAINT simulacion_corrida_etiqueta_check CHECK (etiqueta = 'NO_CALIBRADO'::text)
);

CREATE TABLE IF NOT EXISTS public.simulacion_resultado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_corrida BIGINT NOT NULL,
    id_pecera INTEGER NOT NULL,
    id_especie INTEGER NOT NULL,
    horas_fuera_rango NUMERIC(12,4) NOT NULL,
    factor_dominante TEXT,
    mortalidad_p5_pct NUMERIC(7,4) NOT NULL,
    mortalidad_mediana_pct NUMERIC(7,4) NOT NULL,
    mortalidad_p95_pct NUMERIC(7,4) NOT NULL,
    etiqueta TEXT NOT NULL DEFAULT 'NO_CALIBRADO',
    es_supuesto BOOLEAN NOT NULL DEFAULT TRUE,
    fuente TEXT NOT NULL,
    CONSTRAINT simulacion_resultado_pkey PRIMARY KEY (id),
    CONSTRAINT uq_simulacion_resultado UNIQUE (id_corrida, id_pecera, id_especie),
    CONSTRAINT simulacion_resultado_id_corrida_fkey
        FOREIGN KEY (id_corrida) REFERENCES public.simulacion_corrida(id) ON DELETE CASCADE,
    CONSTRAINT simulacion_resultado_id_especie_fkey
        FOREIGN KEY (id_especie) REFERENCES public.especies(id_especie) ON DELETE RESTRICT,
    CONSTRAINT simulacion_resultado_id_pecera_fkey
        FOREIGN KEY (id_pecera) REFERENCES public.peceras(id_pecera) ON DELETE RESTRICT,
    CONSTRAINT ck_simulacion_resultado_percentiles
        CHECK (mortalidad_p5_pct <= mortalidad_mediana_pct AND mortalidad_mediana_pct <= mortalidad_p95_pct),
    CONSTRAINT simulacion_resultado_etiqueta_check CHECK (etiqueta = 'NO_CALIBRADO'::text),
    CONSTRAINT simulacion_resultado_horas_fuera_rango_check CHECK (horas_fuera_rango >= 0::numeric),
    CONSTRAINT simulacion_resultado_mortalidad_mediana_pct_check
        CHECK (mortalidad_mediana_pct >= 0::numeric AND mortalidad_mediana_pct <= 100::numeric),
    CONSTRAINT simulacion_resultado_mortalidad_p5_pct_check
        CHECK (mortalidad_p5_pct >= 0::numeric AND mortalidad_p5_pct <= 100::numeric),
    CONSTRAINT simulacion_resultado_mortalidad_p95_pct_check
        CHECK (mortalidad_p95_pct >= 0::numeric AND mortalidad_p95_pct <= 100::numeric)
);

